"""Render a Blueprint as a Markdown evidence report."""

from __future__ import annotations

from blueprint_engine.synthesis.blueprint import Blueprint, Evidence, MechanicFinding

KIND_LABEL = {"youtube": "YouTube", "tiktok": "TikTok", "doc": "Roblox Docs", "devforum": "DevForum"}


def fmt_ts(seconds: float | None) -> str:
    if seconds is None:
        return ""
    s = int(seconds)
    return f"{s // 3600}:{s // 60 % 60:02d}:{s % 60:02d}" if s >= 3600 else f"{s // 60}:{s % 60:02d}"


def fmt_num(n: int | None) -> str:
    if n is None:
        return "–"
    for div, suffix in ((1_000_000_000, "B"), (1_000_000, "M"), (1_000, "K")):
        if n >= div:
            return f"{n / div:.1f}{suffix}".replace(".0", "")
    return str(n)


def _md(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def cite(e: Evidence) -> str:
    where = f" @ {fmt_ts(e.start)}" if e.start is not None else ""
    who = f"{e.author} – " if e.author and e.kind != "doc" else ""
    return f"[{_md(who + e.title)}{where}]({e.link}) · {KIND_LABEL.get(e.kind, e.kind)}"


def evidence_bullets(f: MechanicFinding, limit: int = 5) -> list[str]:
    lines = []
    for e in f.evidence[:limit]:
        body = e.tactic or e.quote
        lines.append(f"> “{_md(body)}”  \n> — {cite(e)}" + (f"  \n> ⚠️ *Stale:* {e.stale}" if e.stale else ""))
    return lines


def render_report(bp: Blueprint, top_sources: int = 40) -> str:
    t = bp.totals
    kinds = ", ".join(f"{n} {KIND_LABEL.get(k, k)}" for k, n in sorted(t["by_kind"].items(), key=lambda x: -x[1]))
    out: list[str] = [
        "# Game Design Research — Evidence Report",
        "",
        f"*Auto-generated by `bpe synthesize` on {bp.generated_at} · extractor: `{bp.extractor}`.*  ",
        "*Quotes are short attributed excerpts with deep links (timestamped for video); raw transcripts stay in the local cache.*",
        "",
        "## Run summary",
        "",
        f"- **Sources analysed:** {t['sources']} ({kinds})",
        f"- **Words analysed:** {t['words_analyzed']:,}",
        f"- **Actionable insights extracted:** {t['insights']:,}",
        "- **Transcript origins:** " + ", ".join(f"{k}: {v}" for k, v in sorted(t["transcript_origins"].items())),
        "",
    ]

    if bp.platform_notices:
        out += ["## Platform changes found in first-party docs", ""]
        out += [f"- {_md(n['text'])} — [{_md(n['title'])}]({n['url']})" for n in bp.platform_notices]
        out += ["", "Advice from creators that conflicts with these notices is flagged ⚠️ below.", ""]

    out += ["## Priority overview", "", "| Pillar | P0 mechanics (build first) | P1 |", "|---|---|---|"]
    for p in bp.pillars:
        p0 = ", ".join(f.label for f in p.mechanics if f.priority == "P0") or "–"
        p1 = ", ".join(f.label for f in p.mechanics if f.priority == "P1") or "–"
        out.append(f"| {p.label}{'' if p.focus else ' *(supporting)*'} | {p0} | {p1} |")
    out.append("")

    for p in sorted(bp.pillars, key=lambda p: not p.focus):
        out += [f"## {p.label}", "", f"{p.sources_analyzed} sources · {p.insights} insights", ""]
        out += ["| Priority | Mechanic | Sources (media / docs) | Consensus | Weight |", "|---|---|---|---|---|"]
        for f in p.mechanics:
            out.append(f"| {f.priority} | {f.label} | {f.support} ({f.media_support} / {len(f.doc_support)}) | "
                       f"{f.consensus:.0%} | {f.weight:.2f} |")
        out.append("")
        for f in p.mechanics:
            if f.priority == "P2" and f.support < 2:
                continue
            out += [f"### {f.priority} · {f.label}", ""]
            if f.stale_flags:
                out += [f"> ⚠️ **Platform change:** {s}" for s in f.stale_flags] + [""]
            out += [line + "\n" for line in evidence_bullets(f)]
            if f.metrics:
                out += ["**Numbers cited:** " + "; ".join(f"`{_md(m)}`" for m in f.metrics[:8]), ""]
            if f.playbook:
                pb = f.playbook
                out += ["**Build on Roblox** *(curated playbook)*:", ""]
                out += [f"1. {s}" for s in pb.get("build", [])]
                if pb.get("apis"):
                    out += ["", "**APIs / tools:** " + ", ".join(f"`{a}`" for a in pb["apis"])]
                if pb.get("kpis"):
                    out += ["", "**Measure:** " + "; ".join(pb["kpis"])]
                if pb.get("pitfalls"):
                    out += ["", "**Pitfalls:** " + "; ".join(pb["pitfalls"])]
                out.append("")

    out += ["## Sources (ranked)", "",
            "| # | Source | Kind | Views | Published | Score | Insights |", "|---|---|---|---|---|---|---|"]
    for i, s in enumerate(bp.sources[:top_sources], 1):
        who = f"{s['author']} – " if s["author"] and s["kind"] != "doc" else ""
        out.append(f"| {i} | [{_md(who + s['title'])}]({s['url']}) | {KIND_LABEL.get(s['kind'], s['kind'])} | "
                   f"{fmt_num(s['views'])} | {s['published'] or '–'} | {s['score']:.2f} | {s['insights']} |")
    if len(bp.sources) > top_sources:
        out.append(f"\n*…and {len(bp.sources) - top_sources} more in `blueprint.json`.*")

    out += [
        "", "## Method", "",
        "1. **Discover** — YouTube search per pillar query (yt-dlp), TikTok creator feeds, curated first-party doc pages, DevForum (Discourse API).",
        "2. **Rank** — video score = performance × (0.25 + 0.75 × relevance), where performance = 0.55 view-velocity + "
        "0.25 like-rate + 0.20 channel authority (min-max normalised) and relevance is taxonomy fit scaled by a "
        "developer-intent signal, so viral gameplay videos cannot outrank design content. Docs have a fixed first-party score.",
        "3. **Fetch** — caption tracks via yt-dlp (manual > original-language ASR; machine translations rejected); docs article text.",
        "4. **Extract** — sentence segmentation (punctuation, pauses, discourse markers) → taxonomy classification → actionability "
        "scoring (directives, imperatives, causal reasoning, numbers) → merged evidence passages.",
        "5. **Synthesise** — per mechanic: distinct-source support, weighted by source performance and actionability; P0/P1/P2 tiers; "
        "curated Roblox playbook attached; stale advice checked against first-party deprecation notices.",
        "",
        "**Limitations.** Popularity is not correctness: high-performing videos can still be wrong, which is why first-party docs "
        "are weighted in and stale-advice checks run. The heuristic extractor favours explicit advice; implicit lessons "
        "(shown, not said) need the Claude extractor (`bpe analyze --extractor claude`).",
        "",
    ]
    return "\n".join(out)
